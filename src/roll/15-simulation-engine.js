// ── RAIL ─────────────────────────────────────────────────
// The rail schedule is operator-driven: DB.rail_loading_plan (loading) plus operator pushes in
// DB.rail_movements. Rail v1 used to auto-propose dispatches from a demand-pull projection; the
// rows it wrote are retired here so the board only contains operator pushes. (Idempotent.)
function _railClearAutoProposed(){
  const before=DB.rail_movements.length;
  DB.rail_movements=DB.rail_movements.filter(m=>m.notes!=='Auto-generated by simulation');
  if(DB.rail_movements.length!==before) autoSave();
}

// Day-by-day silo projection for the vessel auto-proposer, mirroring simDayBerths: ONE vessel docked
// at a time (a vessel arriving meanwhile queues at anchorage, FIFO), and ship berths discharge
// ALL-OR-NOTHING each day — a full day at the berth rate if the silo has room (today's drain counts),
// otherwise nothing; anti-deadlock: a day's rate bigger than the whole silo takes whatever room exists.
// A vessel's cargo is never clipped: it stays aboard until it fits. (Clipping it made the proposer
// think the silo drained sooner than it really does, so every later vessel was proposed earlier
// and earlier.) The simulator's berth-yield swap is not modelled (one product per berth).
function _projectShipSilo(vessels, startInv, siloMax, outflow, horizon, projInv, intake){
  const vs=vessels.slice().sort((a,b)=>a.arr-b.arr);
  let vi=0, cur=null, rem=0, inv=startInv;
  for(let d=1;d<=horizon;d++){
    projInv[d]=inv;
    if(!cur||rem<=0){
      if(vi<vs.length&&vs[vi].arr<=d){cur=vs[vi++];rem=cur.qty;} else cur=null;
    }
    let take=0;
    if(cur&&rem>0){
      const fullDaily=Math.min(cur.perDay, rem), space=Math.max(0,siloMax-inv+outflow[d]);
      take=space>=fullDaily?fullDaily:(fullDaily>siloMax?space:0);
      rem-=take;
    }
    intake[d]=take;
    inv=Math.max(0,Math.min(siloMax,inv+take-outflow[d]));
  }
  projInv[horizon+1]=inv;
}

function _writeProposedVesselCalls(r){
  // Remove only AUTO-GENERATED Proposed vessel calls (notes starts with 'Auto-proposed').
  // User-created Proposed vessels (e.g. placeholders/estimates) are preserved so the
  // auto-proposer treats them as covering that date window, preventing duplicates.
  DB.vessel_calls=DB.vessel_calls.filter(v=>
    v.status!=='Proposed'||!(v.notes?.startsWith('Auto-proposed'))
  );

  const simStart=new Date(S.simCfg.start_date+'T12:00:00'); // noon-anchored, DST-safe (see simStartDate)
  const horizon=r?.simHorizon||S.simCfg.horizon;
  const allEls=getFacElements();
  const allConns=getFacConnections();

  // Build downstream map
  const dn={};
  allConns.forEach(c=>{
    if(!dn[c.from_element_id]) dn[c.from_element_id]=[];
    dn[c.from_element_id].push(c.to_element_id);
  });
  const elMap=Object.fromEntries(allEls.map(e=>[e.id,e]));

  allEls.filter(e=>e.type==='supply_source'&&(e.props.supply_mode||'Ship')==='Ship').forEach(ss=>{
    const productId=ss.props.product_id; if(!productId) return;
    const typicalVol=parseFloat(ss.props.typical_volume_t)||0; if(!typicalVol) return;
    const leadDays=Math.max(1, parseInt(ss.props.lead_time_days)||1);
    const minCoverDays=parseInt(ss.props.min_cover_days)||7;
    const prod=DB.products.find(p=>p.id===productId);

    const downBerths=(dn[ss.id]||[]).map(id=>elMap[id]).filter(e=>e&&e.type==='berth');
    const berthAllocs=ss.props.berth_allocations||null;
    // Only berths this source still connects to: removing a link leaves its old split behind in the props
    // (MEDCEM kept {PEV:125, SUT:100} after losing SUT, so every proposed ship carried 225 t).
    const allocBerths=Object.entries(berthAllocs||{})
      .map(([berthId,qty])=>({berth:elMap[berthId],qty:parseFloat(qty)||0}))
      .filter(x=>x.berth&&x.qty>0&&downBerths.includes(x.berth));

    // A split over two or more connected berths → propose split vessels
    // Otherwise → propose independent full vessels per berth (original behaviour)
    if(allocBerths.length>1){
      // Split mode: one vessel call with legs. Use the PRIMARY berth (largest allocation)
      // for trigger calculation; all berths share the lead time.

      // Use the largest allocation berth as the primary for inventory trigger
      const primary=allocBerths.reduce((a,b)=>b.qty>a.qty?b:a);
      const primaryBerth=primary.berth;
      const primaryQty=primary.qty;
      const berthRate=parseFloat(primaryBerth.props.max_unload_rate_tph)||0;
      const unloadDays=berthRate>0?Math.ceil(primaryQty/(berthRate*24)):3;

      const downSilos=(dn[primaryBerth.id]||[]).map(id=>elMap[id]).filter(e=>e&&e.type==='bulk_silo');
      const targetSilo=downSilos.find(s=>(s.props.products||[]).includes(productId))||downSilos[0];
      if(!targetSilo) return;

      const siloMax=parseFloat(targetSilo.props.max_capacity)||0; if(!siloMax) return;
      const siloStart=parseFloat(targetSilo.props.start_inventory)||0;
      const _objSp=targetSilo.props?.inventory_objective||'maximize';
      const targetInvSp=({maximize:1.00,meet_demand:0.75,minimize:0.50}[_objSp]??1.00)*siloMax;

      const demIds=[];
      const visited=new Set([targetSilo.id]);
      const q=[targetSilo.id];
      while(q.length){
        const cur=q.shift();
        (dn[cur]||[]).forEach(tid=>{
          if(visited.has(tid)) return; visited.add(tid);
          const te=elMap[tid]; if(!te) return;
          if(te.type==='demand_point') demIds.push(te.id);
          else if(te.type==='dispatch_point') q.push(tid);
        });
      }

      const dailyOutflow=new Array(horizon+2).fill(0);
      for(let d=1;d<=horizon;d++){
        const dt=new Date(simStart.getTime()+(d-1)*864e5);
        const ds=dt._ymd();
        dailyOutflow[d]=demIds.reduce((s,id)=>s+(_demandRate(id,ds)||0),0);
      }
      const totDemSp=dailyOutflow.reduce((s,v)=>s+v,0);
      if(totDemSp<=0) return;
      const critFloorSp=minCoverDays*(totDemSp/horizon);

      const lockedCalls=DB.vessel_calls.filter(v=>
        allocBerths.some(ab=>v.berth_element_id===ab.berth.id||
          (v.legs||[]).some(l=>l.berth_element_id===ab.berth.id))
        &&v.product_id===productId
        &&(v.status!=='Proposed'||!(v.notes?.startsWith('Auto-proposed')))
      );
      const lockedVsSp=[];
      lockedCalls.forEach(v=>{
        const arrDay=dateToDayOffset(v.arrival_date,S.simCfg.start_date)+1;
        if(arrDay<1) return;
        lockedVsSp.push({arr:arrDay, qty:primaryQty, perDay:berthRate>0?berthRate*24:primaryQty/unloadDays});
      });

      const propVsSp=[];
      const proposedCalls=[];
      const projInvSp=new Array(horizon+2).fill(0);
      const intakeSp=new Array(horizon+2).fill(0);
      const startInvSp=Math.max(0,Math.min(siloMax,siloStart));
      const rebuildFromSp=()=>_projectShipSilo([...lockedVsSp,...propVsSp],startInvSp,siloMax,dailyOutflow,horizon,projInvSp,intakeSp);
      rebuildFromSp();

      let scanFromSp=1, guardSp=horizon+10;
      while(guardSp-->0){
        let critDay=null;
        for(let d=scanFromSp;d<=horizon;d++){
          const eod=projInvSp[d+1];
          if(eod<=critFloorSp){critDay=d;break;}
        }
        if(!critDay) break;

        const idealArrival=critDay;
        const orderDay=idealArrival-leadDays;
        if(orderDay<1||idealArrival>horizon){scanFromSp=critDay+1;continue;}

        const projAtArrival=projInvSp[idealArrival];
        if(projAtArrival>=targetInvSp*0.95){scanFromSp=critDay+1;continue;}

        const alreadyCovered=[...lockedCalls,...proposedCalls].some(v=>{
          const ad=v.arrivalDay??dateToDayOffset(v.arrival_date,S.simCfg.start_date)+1;
          return ad>=idealArrival-unloadDays&&ad<=idealArrival+2;
        });
        if(alreadyCovered){scanFromSp=critDay+1;continue;}

        const arrivalStr=new Date(simStart.getTime()+(idealArrival-1)*864e5)._ymd();
        const orderStr=new Date(simStart.getTime()+(orderDay-1)*864e5)._ymd();
        proposedCalls.push({arrivalDay:idealArrival});
        propVsSp.push({arr:idealArrival, qty:primaryQty, perDay:berthRate>0?berthRate*24:primaryQty/Math.max(1,unloadDays)});
        rebuildFromSp();

        let legOffset=0;
        const legs=allocBerths.map((ab,li)=>{
          if(li>0) legOffset+=berthRate>0?Math.ceil(allocBerths[li-1].qty/(berthRate*24)):unloadDays;
          const legArrival=new Date(simStart.getTime()+(idealArrival-1+legOffset)*864e5)._ymd();
          const legBerth=ab.berth;
          return {
            berth_element_id:legBerth.id,
            arrival_date:legArrival,
            quantity_t:ab.qty,
            unload_rate_tph:parseFloat(legBerth.props.max_unload_rate_tph)||0,
            status:'Proposed'
          };
        });

        const firstLegBerth=allocBerths[0].berth;
        DB.vessel_calls.push({
          id:`vc_prop_${ss.id}_${idealArrival}`,
          facility_id:firstLegBerth.assigned_facility_id||firstLegBerth.facility_id||S.facility_id,
          name:`PROP-SPLIT-${prod?.name||productId}-${arrivalStr}`,
          product_id:productId,
          cargo_type:prod?.name||productId,
          total_quantity_t:typicalVol,
          quantity_t:typicalVol,
          berth_element_id:legs[0].berth_element_id,
          arrival_date:legs[0].arrival_date,
          unload_rate_tph:legs[0].unload_rate_tph,
          legs,
          transit_days:leadDays,
          notes:`Auto-proposed split. Order by: ${orderStr}`,
          status:'Proposed'
        });

        scanFromSp=1;
      }
      return; // done with this supply source — skip individual berth loop
    }

    // Individual berth mode (no allocation config or single berth)
    downBerths.forEach(berth=>{
      const berthRate=parseFloat(berth.props.max_unload_rate_tph)||0;
      const unloadDays=berthRate>0?Math.ceil(typicalVol/(berthRate*24)):3;

      // Target silo for this product
      const downSilos=(dn[berth.id]||[]).map(id=>elMap[id]).filter(e=>e&&e.type==='bulk_silo');
      const targetSilo=downSilos.find(s=>(s.props.products||[]).includes(productId))||downSilos[0];
      if(!targetSilo) return;

      const siloMax=parseFloat(targetSilo.props.max_capacity)||0; if(!siloMax) return;
      const siloStart=parseFloat(targetSilo.props.start_inventory)||0;
      const _obj=targetSilo.props?.inventory_objective||'maximize';
      const targetInv=({maximize:1.00,meet_demand:0.75,minimize:0.50}[_obj]??1.00)*siloMax;

      const demIds=[];
      const visited=new Set([targetSilo.id]);
      const q=[targetSilo.id];
      while(q.length){
        const cur=q.shift();
        (dn[cur]||[]).forEach(tid=>{
          if(visited.has(tid)) return;
          visited.add(tid);
          const te=elMap[tid];
          if(!te) return;
          if(te.type==='demand_point') demIds.push(te.id);
          else if(te.type==='dispatch_point') q.push(tid);
        });
      }

      const dailyOutflow=new Array(horizon+2).fill(0);
      for(let d=1;d<=horizon;d++){
        const dt=new Date(simStart.getTime()+(d-1)*864e5);
        const ds=dt._ymd();
        dailyOutflow[d]=demIds.reduce((s,id)=>s+(_demandRate(id,ds)||0),0);
      }
      const totalDemand=dailyOutflow.reduce((s,v)=>s+v,0);
      if(totalDemand<=0) return;
      const critFloor=minCoverDays*(totalDemand/horizon);

      const lockedCalls=DB.vessel_calls.filter(v=>
        v.berth_element_id===berth.id&&v.product_id===productId&&
        (v.status!=='Proposed'||!(v.notes?.startsWith('Auto-proposed')))
      );
      const lockedVs=[];
      lockedCalls.forEach(v=>{
        const arrDay=dateToDayOffset(v.arrival_date,S.simCfg.start_date)+1;
        if(arrDay<1) return;
        const rate=parseFloat(v.unload_rate_tph)||berthRate;
        const ud=rate>0?Math.ceil((v.quantity_t||0)/(rate*24)):unloadDays;
        lockedVs.push({arr:arrDay, qty:v.quantity_t||0, perDay:rate>0?rate*24:(v.quantity_t||0)/ud});
      });

      const propVs=[];
      const proposedCalls=[];

      // Forward projection: projInv[d] = BOD inventory on day d; intake[d] = tonnes unloaded on day d
      const projInv=new Array(horizon+2).fill(0);
      const intake=new Array(horizon+2).fill(0);
      const startInvB=Math.max(0,Math.min(siloMax,siloStart));
      const rebuildFrom=()=>_projectShipSilo([...lockedVs,...propVs],startInvB,siloMax,dailyOutflow,horizon,projInv,intake);
      rebuildFrom();

      const facName=DB.facilities.find(f=>f.id===(berth.assigned_facility_id||berth.facility_id||S.facility_id))?.name||'';
      const vesselFacId=berth.assigned_facility_id||berth.facility_id||S.facility_id;
      let scanFrom=1, guard=horizon+10;

      while(guard-->0){
        // Find first day where EOD inventory hits the critical floor
        let critDay=null;
        for(let d=scanFrom;d<=horizon;d++){
          const eod=projInv[d+1];
          if(eod<=critFloor){critDay=d;break;}
        }
        if(!critDay) break;

        const idealArrival=critDay;
        const orderDay=idealArrival-leadDays;
        if(orderDay<1||idealArrival>horizon){scanFrom=critDay+1;continue;}

        // Skip if silo will already be near or above target at arrival
        const projAtArrival=projInv[idealArrival];
        if(projAtArrival>=targetInv*0.95){scanFrom=critDay+1;continue;}

        // Skip if a vessel is already arriving close enough to cover this period
        const alreadyCovered=[...lockedCalls,...proposedCalls].some(v=>{
          const ad=v.arrivalDay??dateToDayOffset(v.arrival_date,S.simCfg.start_date)+1;
          return ad>=idealArrival-unloadDays&&ad<=idealArrival+2;
        });
        if(alreadyCovered){scanFrom=critDay+1;continue;}

        const arrivalStr=new Date(simStart.getTime()+(idealArrival-1)*864e5)._ymd();
        const orderStr=new Date(simStart.getTime()+(orderDay-1)*864e5)._ymd();

        proposedCalls.push({arrivalDay:idealArrival});
        propVs.push({arr:idealArrival, qty:typicalVol, perDay:berthRate>0?berthRate*24:typicalVol/Math.max(1,unloadDays)});
        rebuildFrom();

        DB.vessel_calls.push({
          id:`vc_prop_${ss.id}_${berth.id}_${idealArrival}`,
          facility_id:vesselFacId,
          berth_element_id:berth.id,
          berth_name:berth.name,
          name:`PROP-${facName}-${prod?.name||productId}-${arrivalStr}`,
          arrival_date:arrivalStr,
          product_id:productId,
          cargo_type:prod?.name||productId,
          quantity_t:typicalVol,
          unload_rate_tph:berthRate,
          transit_days:leadDays,
          notes:`Auto-proposed. Order by: ${orderStr}`,
          status:'Proposed'
        });

        scanFrom=1; // restart scan — projection updated
      }
    });
  });

  autoSave();
}

