  // Per-silo stop level (target inventory): uses target_pct prop if set, else objective default
  // ovPct (optional) = a mill-policy override of the target %, takes precedence over silo prop.
  function siloTarget(el, ovPct){
    const s=state[el.id];
    if(!s||s.maxCap<=0) return 0;
    if(ovPct!=null) return (parseFloat(ovPct)||0)/100 * s.maxCap;
    const obj=el.props.inventory_objective||'maximize';
    if(el.props.target_pct!=null&&el.props.target_pct!==''&&parseFloat(el.props.target_pct)>0){
      return (parseFloat(el.props.target_pct)||0)/100 * s.maxCap;
    }
    return (defaultTargetPct[obj]||1.00)*s.maxCap;
  }

  // Per-silo critical floor: uses critical_floor_pct prop if set, else 10%.
  // ovPct (optional) = a mill-policy override, takes precedence.
  function siloCriticalFloor(el, ovPct){
    const s=state[el.id];
    if(!s||s.maxCap<=0) return 0;
    if(ovPct!=null) return (parseFloat(ovPct)||0)/100 * s.maxCap;
    if(el.props.critical_floor_pct!=null&&el.props.critical_floor_pct!==''){
      return (parseFloat(el.props.critical_floor_pct)||0)/100 * s.maxCap;
    }
    return defaultFloorPct * s.maxCap;
  }

  // Daily depletion rate for a silo — FORWARD-LOOKING: average forecast demand
  // over the NEXT 14 days (future requirements, not past outflow). The window
  // starts at "today" = current day offset = s.outflowHistory.length (entries
  // accumulate one per completed day, so its length equals the current 0-based day).
  function siloRate(siloId, lookaheadDays){
    const s=state[siloId]; const el=elMap[siloId];
    if(!s||!el) return 0;
    const win=(lookaheadDays&&lookaheadDays>0)?Math.round(lookaheadDays):14;
    const prods=getSiloProducts(el);
    const startIdx=Math.max(0,s.outflowHistory.length);
    return demandPoints.filter(dp=>dp.products.some(pid=>prods.includes(pid)))
      .reduce((sum,dp)=>{
        const slice=dp.dailyRates.slice(startIdx,startIdx+win);
        const avg=slice.length?slice.reduce((a,b)=>a+b,0)/slice.length:0;
        return sum+avg;
      },0);
  }

  // Net depletion rate: demand minus what other mills still send into this silo
  function netDepletion(siloId, excludeMillId, lookaheadDays){
    const siloEl=elMap[siloId];
    let rate=siloRate(siloId, lookaheadDays);
    (up[siloId]||[]).forEach(uid=>{
      const upEl=elMap[uid];
      if(!upEl||upEl.type!=='finish_mill'||upEl.id===excludeMillId) return;
      const cp=state[uid]?.currentProduct;
      if(cp&&getSiloProducts(siloEl).includes(cp)){
        const c=(capMap[uid]||[]).find(x=>x.product_id===cp);
        if(c) rate-=(c.capacity_tpd||0);
      }
    });
    return Math.max(0,rate);
  }

  // Days until silo empties if excluded mill stops serving it

  // Urgency = how many days of FM production needed to reach the stop level.
  // Higher = more urgent = mill should produce for this silo.
  // Returns 0 when inventory is at or above stop level (objective satisfied).
  // excludeMillId = the mill being evaluated (excluded from "other mill" inflow calc)
  // ovTargetPct + lookaheadDays (optional) come from an active mill-policy override.
  function urgency(siloId, excludeMillId, ovTargetPct, lookaheadDays){
    const s=state[siloId]; const el=elMap[siloId];
    if(!s||!el||s.maxCap<=0) return 0;
    const stop=siloTarget(el, ovTargetPct);
    if(s.inventory>=stop) return 0; // satisfied
    const nd=netDepletion(siloId,excludeMillId,lookaheadDays);
    if(nd<=0) return 0.001; // self-sustaining but not at stop — tiny urgency
    return (stop-s.inventory)/nd;
  }

  function isCritical(siloId, excludeMillId, ovFloorPct, lookaheadDays){
    const s=state[siloId]; const el=elMap[siloId];
    if(!s) return false;
    if(s.maxCap<=0) return false; // zero/disabled silo — never block production for it
    const floor=siloCriticalFloor(el, ovFloorPct);
    if(s.inventory<=floor) return true; // below critical floor — always urgent
    const nd=netDepletion(siloId,excludeMillId,lookaheadDays);
    if(nd<=0) return false;
    return (s.inventory/nd)<1;
  }


