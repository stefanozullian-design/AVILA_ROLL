  // Daily outflow rate for a silo.
  // Uses rolling 10-day average when available; falls back to configured demand.
  // Stop level for each objective
  // Default target levels by objective — overridden per silo by target_pct prop
  const defaultTargetPct={maximize:1.00, meet_demand:0.75, minimize:0.50};
